CREATE TABLE IF NOT EXISTS public."SCD_Report_Logbook" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW(),
    tanggal DATE NOT NULL,
    waktu_mulai TIME,
    waktu_selesai TIME,
    program VARCHAR(150) NOT NULL,
    kategori VARCHAR(100) NOT NULL, -- 'Rapat & Koordinasi', 'Pelatihan & Pemberdayaan', 'Pekerjaan Teknis/Lapangan', 'Penyaluran Bantuan/Alat', 'Penanganan Masalah (Troubleshooting)', 'Administrasi & Pelaporan', 'Lainnya'
    judul VARCHAR(255) NOT NULL,
    lokasi VARCHAR(255),
    pic_nama VARCHAR(150) NOT NULL, -- Nama PIC Lapangan pelaksana kegiatan
    kelompok_binaan VARCHAR(150),  -- Nama Kelompok Binaan (Kelompok Tani, KWT, dll.)
    stakeholder TEXT,              -- Stakeholder / Pihak Lainnya (Pemdes, Dinas, Vendor, dll.)
    ketua_kelompok VARCHAR(150),   -- (Kompatibilitas data)
    tim_pendamping TEXT,           -- (Kompatibilitas data)
    pihak_terlibat TEXT,           -- (Kompatibilitas data)
    jumlah_peserta INTEGER DEFAULT 0,
    uraian_kegiatan TEXT NOT NULL,
    output_capaian TEXT,
    status VARCHAR(50) DEFAULT 'Selesai', -- 'Selesai', 'Berjalan', 'Ada Kendala'
    kendala TEXT,
    tindak_lanjut TEXT,
    items JSONB DEFAULT '[]'::jsonb,             -- Rincian baris dinamis: [{"no": 1, "output_capaian": "...", "kendala": "...", "tindak_lanjut": "..."}]
    foto_dokumentasi JSONB DEFAULT '[]'::jsonb, -- Array foto kegiatan: [{"url": "...", "name": "..."}]
    link_lampiran TEXT,                          -- Tautan Google Drive dokumen pendukung/notulen
    created_by VARCHAR(150) DEFAULT 'comdevptba@gmail.com'
);

-- Kolom tambahan jika tabel sudah pernah dibuat sebelumnya (Migrasi Skema):
ALTER TABLE public."SCD_Report_Logbook" 
ADD COLUMN IF NOT EXISTS items JSONB DEFAULT '[]'::jsonb,
ADD COLUMN IF NOT EXISTS kelompok_binaan VARCHAR(150),
ADD COLUMN IF NOT EXISTS ketua_kelompok VARCHAR(150),
ADD COLUMN IF NOT EXISTS stakeholder TEXT,
ADD COLUMN IF NOT EXISTS jumlah_peserta INTEGER DEFAULT 0;

-- ==============================================================================
-- INDEXING UNTUK PERFORMA PENCARIAN & FILTER CEPAT
-- ==============================================================================
CREATE INDEX IF NOT EXISTS idx_scd_logbook_program ON public."SCD_Report_Logbook" (program);
CREATE INDEX IF NOT EXISTS idx_scd_logbook_tanggal ON public."SCD_Report_Logbook" (tanggal DESC);
CREATE INDEX IF NOT EXISTS idx_scd_logbook_kategori ON public."SCD_Report_Logbook" (kategori);
CREATE INDEX IF NOT EXISTS idx_scd_logbook_status ON public."SCD_Report_Logbook" (status);
CREATE INDEX IF NOT EXISTS idx_scd_logbook_pic ON public."SCD_Report_Logbook" (pic_nama);

