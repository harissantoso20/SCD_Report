CREATE TABLE IF NOT EXISTS public."SCD_Report_Monitoring" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    tanggal DATE NOT NULL,
    hari VARCHAR(30),
    program VARCHAR(150) NOT NULL,
    lokasi VARCHAR(255),
    keterangan TEXT,
    items JSONB DEFAULT '[]'::jsonb, -- Berisi array: [{ no: 1, uraian: "...", kendala: "...", tindak_lanjut: "..." }]
    pic_sustainability VARCHAR(150),
    penerima_manfaat VARCHAR(150),
    created_by VARCHAR(150),
    foto_dokumentasi JSONB DEFAULT '[]'::jsonb, -- Array URL/Foto Eviden Kegiatan: ["url1", "url2"]
    scan_daftar_hadir JSONB DEFAULT '[]'::jsonb  -- Array URL/Foto Scan Daftar Hadir: ["url1", "url2"]
);

-- Kolom tambahan eviden jika tabel sudah pernah dibuat sebelumnya:
ALTER TABLE public."SCD_Report_Monitoring" 
ADD COLUMN IF NOT EXISTS foto_dokumentasi JSONB DEFAULT '[]'::jsonb,
ADD COLUMN IF NOT EXISTS scan_daftar_hadir JSONB DEFAULT '[]'::jsonb;

-- Indexing untuk pencarian cepat berdasarkan program dan tanggal
CREATE INDEX IF NOT EXISTS idx_scd_monitoring_program ON public."SCD_Report_Monitoring" (program);
CREATE INDEX IF NOT EXISTS idx_scd_monitoring_tanggal ON public."SCD_Report_Monitoring" (tanggal DESC);

-- Kebijakan Akses Keamanan (Row Level Security)
ALTER TABLE public."SCD_Report_Monitoring" ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow public read access" 
ON public."SCD_Report_Monitoring" 
FOR SELECT 
USING (true);

CREATE POLICY "Allow public insert access" 
ON public."SCD_Report_Monitoring" 
FOR INSERT 
WITH CHECK (true);

CREATE POLICY "Allow public update access" 
ON public."SCD_Report_Monitoring" 
FOR UPDATE 
USING (true);

CREATE POLICY "Allow public delete access" 
ON public."SCD_Report_Monitoring" 
FOR DELETE 
USING (true);
